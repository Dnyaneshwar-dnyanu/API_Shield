CREATE TABLE IF NOT EXISTS `request_logs` (
    `id` BIGINT AUTO_INCREMENT NOT NULL,
    `request_id` VARCHAR(36) NOT NULL,
    `api_id` VARCHAR(36) NOT NULL,
    `api_slug` VARCHAR(100) NULL,
    `developer_id` VARCHAR(36) NULL,
    `subscription_id` VARCHAR(36) NULL,
    `api_key_id` VARCHAR(36) NULL,
    `endpoint_path` VARCHAR(500) NOT NULL,
    `http_method` VARCHAR(10) NOT NULL,
    `status_code` INT NOT NULL,
    `latency_ms` INT NOT NULL,
    `client_ip` VARCHAR(45) NULL,
    `user_agent` VARCHAR(255) NULL,
    `error_message` VARCHAR(500) NULL,
    `timestamp` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_req_id` (`request_id`),
    INDEX `idx_log_api_id` (`api_id`),
    INDEX `idx_log_developer_id` (`developer_id`),
    INDEX `idx_log_timestamp` (`timestamp`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `usage_statistics` (
    `id` BIGINT AUTO_INCREMENT NOT NULL,
    `api_id` VARCHAR(36) NOT NULL,
    `developer_id` VARCHAR(36) NOT NULL,
    `plan_id` VARCHAR(36) NULL,
    `period_date` DATE NOT NULL,
    `period_hour` INT NULL,
    `total_requests` BIGINT NOT NULL DEFAULT 0,
    `successful_requests` BIGINT NOT NULL DEFAULT 0,
    `client_errors` BIGINT NOT NULL DEFAULT 0,
    `server_errors` BIGINT NOT NULL DEFAULT 0,
    `blocked_rate_limit` BIGINT NOT NULL DEFAULT 0,
    `blocked_auth` BIGINT NOT NULL DEFAULT 0,
    `avg_latency_ms` INT NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_api_dev_period` (`api_id`, `developer_id`, `period_date`, `period_hour`),
    INDEX `idx_usage_api_date` (`api_id`, `period_date`),
    INDEX `idx_usage_dev_date` (`developer_id`, `period_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
